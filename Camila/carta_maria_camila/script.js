$('openBtn').addEventListener('click', () => {
  intro.classList.add('hidden');
  letter.classList.remove('hidden');
  scrollTo({ top: 0, behavior: 'auto' });
  observeAll();
  updateProgress();
  show(9);
});

const stage = $('stage');
function stageLaunch(e) {
  const pt = e.touches ? e.touches[0] : e;
  const r = stage.getBoundingClientRect();
  const x = pt ? pt.clientX : r.left + r.width / 2;
  const y = pt ? pt.clientY : r.top + r.height / 2;
  launch(x, y);
}
stage.addEventListener('pointerdown', stageLaunch);
stage.addEventListener('keydown', e => {
  if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); launch(W / 2, H * 0.3); }
});

$('moreBtn').addEventListener('click', () => show(12));
$('topBtn').addEventListener('click', () => scrollTo({ top: 0, behavior: 'smooth' }));

