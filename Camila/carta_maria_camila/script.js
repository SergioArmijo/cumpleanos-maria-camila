/* ---------- Aparición al hacer scroll ---------- */
const io = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
  });
}, { threshold: 0.12 });
function observeAll() {
  document.querySelectorAll('.reveal, .note').forEach(el => io.observe(el));
}

