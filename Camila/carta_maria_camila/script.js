/* ---------- Fuegos artificiales ---------- */
const cv = $('fx'), ctx = cv.getContext('2d');
let W = 0, H = 0, dpr = 1;
function resize() {
  dpr = Math.min(window.devicePixelRatio || 1, 2);
  W = innerWidth; H = innerHeight;
  cv.width = W * dpr; cv.height = H * dpr;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
}
addEventListener('resize', resize);
resize();

const COLORS = ['#e5251b', '#f7cf1f', '#1fa335', '#ff7a1a', '#ff3d8b', '#7b3fe4', '#19a7ce'];
const rand = (a, b) => a + Math.random() * (b - a);
const pick = a => a[Math.floor(Math.random() * a.length)];
const TAU = Math.PI * 2;

let rockets = [], sparks = [], running = false, last = 0;

function launch(x, y) {
  const sx = x + rand(-30, 30);
  const ty = y;
  const dist = H - ty;
  const vy = -Math.sqrt(2 * 0.12 * Math.max(dist, 120)); // sube hasta la altura deseada
  rockets.push({ x: sx, y: H + 10, vx: (x - sx) * 0.004, vy, ty, col: pick(COLORS), trail: [] });
  start();
}

function explode(x, y, col) {
  const small = W < 520;
  const n = small ? 56 : 90;
  const type = Math.random();
  const col2 = pick(COLORS);
  for (let i = 0; i < n; i++) {
    let vx, vy, c = col;
    const a = (i / n) * TAU;
    if (type < 0.3) {                       // esfera
      const s = rand(1.5, 5.2); vx = Math.cos(a) * s; vy = Math.sin(a) * s;
    } else if (type < 0.55) {               // anillo de dos colores
      const s = i % 2 ? 4.2 : 2.6; vx = Math.cos(a) * s; vy = Math.sin(a) * s; c = i % 2 ? col : col2;
    } else if (type < 0.75) {               // corazón
      vx = 0.28 * 16 * Math.pow(Math.sin(a), 3);
      vy = -0.28 * (13 * Math.cos(a) - 5 * Math.cos(2 * a) - 2 * Math.cos(3 * a) - Math.cos(4 * a));
    } else {                                // sauce
      const s = rand(1, 4.6); vx = Math.cos(a) * s; vy = Math.sin(a) * s - 1;
      sparks.push({ x, y, vx, vy, life: 0, max: rand(80, 120), col: '#f7cf1f', trail: [], g: 0.05, w: 2 });
      continue;
    }
    sparks.push({ x, y, vx, vy, life: 0, max: rand(55, 85), col: c, trail: [], g: 0.045, w: 2.4 });
  }
}

function frame(t) {
  const dt = Math.min(2.5, (t - last) / 16.67 || 1);
  last = t;
  ctx.clearRect(0, 0, W, H);
  ctx.lineCap = 'round';

  rockets = rockets.filter(r => {
    r.trail.push([r.x, r.y]); if (r.trail.length > 8) r.trail.shift();
    r.x += r.vx * dt * 16; r.y += r.vy * dt; r.vy += 0.12 * dt;
    drawTrail(r.trail, r.col, 3, 1);
    if (r.vy >= -1 || r.y <= r.ty) { explode(r.x, r.y, r.col); return false; }
    return true;
  });

  sparks = sparks.filter(s => {
    s.trail.push([s.x, s.y]); if (s.trail.length > 6) s.trail.shift();
    s.vx *= Math.pow(0.985, dt); s.vy *= Math.pow(0.985, dt);
    s.x += s.vx * dt; s.y += s.vy * dt; s.vy += s.g * dt; s.life += dt;
    const k = 1 - s.life / s.max;
    if (k <= 0) return false;
    drawTrail(s.trail, s.col, s.w * (0.5 + k), k);
    return true;
  });

  if (rockets.length || sparks.length) requestAnimationFrame(frame);
  else { running = false; ctx.clearRect(0, 0, W, H); }
}
function drawTrail(tr, col, w, alpha) {
  if (tr.length < 2) return;
  ctx.strokeStyle = col; ctx.lineWidth = w; ctx.globalAlpha = Math.max(0, alpha);
  ctx.beginPath(); ctx.moveTo(tr[0][0], tr[0][1]);
  for (let i = 1; i < tr.length; i++) ctx.lineTo(tr[i][0], tr[i][1]);
  ctx.stroke(); ctx.globalAlpha = 1;
}
function start() { if (!running) { running = true; last = performance.now(); requestAnimationFrame(frame); } }

/* Función de espectáculo: varios cohetes escalonados */
function show(n = 8) {
  for (let i = 0; i < n; i++) {
    setTimeout(() => launch(rand(W * 0.12, W * 0.88), rand(H * 0.12, H * 0.5)), i * 380 + rand(0, 200));
  }
}

